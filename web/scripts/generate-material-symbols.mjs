/**
 * Material Symbols (Rounded, weight 400) icon generator
 *
 * 扫描 src/ 下所有 `@/components/md3/icons` 导入里的图标常量名（形如 `mdSearch`、
 * `mdHomeFill`、`mdArrowBack`），从 @material-symbols/svg-400/rounded 抽取对应
 * SVG path，生成 src/components/md3/icons.generated.ts。
 *
 * 命名规则：md + PascalCase(symbol_name) [+ "Fill"]
 *   search            → mdSearch
 *   arrow_back        → mdArrowBack
 *   home (filled)     → mdHomeFill
 *   10k               → md10k
 *
 * 这样只有真正用到的图标会进入产物，SSR 直接输出内联 <svg>，无需图标字体。
 *
 * 使用方法: bun scripts/generate-material-symbols.mjs
 */

import fs from "fs";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(__dirname, "..");
const srcRoot = path.join(webRoot, "src");
const outPath = path.join(srcRoot, "components/md3/icons.generated.ts");
const require = createRequire(import.meta.url);
const symbolsDir = path.join(path.dirname(require.resolve("@material-symbols/svg-400/package.json")), "rounded");

/** Icons always generated (used by md3 primitives themselves). */
const BASE_ICONS = [
    "mdClose", "mdCheck", "mdKeyboardArrowDown", "mdKeyboardArrowUp", "mdSearch", "mdChevronLeft", "mdChevronRight",
    "mdArrowBack", "mdArrowUpward", "mdArrowDownward", "mdMenu", "mdMenuOpen", "mdMoreVert", "mdCancel",
    "mdErrorFill", "mdInfo", "mdRemove", "mdAdd", "mdCheckBoxOutlineBlank", "mdCheckBox", "mdIndeterminateCheckBox",
];

function walk(dir, out = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            if (entry.name === "vendor" || entry.name === "node_modules") continue;
            walk(full, out);
        } else if (/\.(tsx?|mjs)$/.test(entry.name) && !entry.name.endsWith(".generated.ts")) {
            out.push(full);
        }
    }
    return out;
}

const IMPORT_RE = /import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*["'](?:@\/components\/md3\/icons|\.\/icons|\.\.\/md3\/icons)["']/g;

const wanted = new Set(BASE_ICONS);
for (const file of walk(srcRoot)) {
    const text = fs.readFileSync(file, "utf8");
    for (const m of text.matchAll(IMPORT_RE)) {
        for (const raw of m[1].split(",")) {
            const name = raw.trim().split(/\s+as\s+/)[0].trim();
            if (/^md[0-9A-Z]/.test(name)) wanted.add(name);
        }
    }
}

/** mdArrowBackFill → { file: "arrow_back-fill.svg" } ; tries both camel splits. */
function resolveIcon(constName) {
    let base = constName.slice(2);
    let fill = false;
    if (base.endsWith("Fill")) {
        fill = true;
        base = base.slice(0, -4);
    }
    const snake = base
        .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
        .replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
        .toLowerCase();
    // Digits are ambiguous ("inventory_2", "10k", "counter_1"): try separated and joined forms.
    const withDigitSep = snake.replace(/([a-z])(\d)/g, "$1_$2");
    const candidates = [snake, withDigitSep, snake.replace(/_(\d)/g, "$1"), snake.replace(/(\d)_/g, "$1")];
    for (const c of candidates) {
        const file = path.join(symbolsDir, `${c}${fill ? "-fill" : ""}.svg`);
        if (fs.existsSync(file)) return { file, symbol: c, fill };
    }
    return null;
}

const entries = [];
const missing = [];
for (const name of [...wanted].sort()) {
    const resolved = resolveIcon(name);
    if (!resolved) {
        missing.push(name);
        continue;
    }
    const svg = fs.readFileSync(resolved.file, "utf8");
    const d = svg.match(/<path d="([^"]+)"/)?.[1];
    if (!d) {
        missing.push(name);
        continue;
    }
    entries.push(`/** ${resolved.symbol}${resolved.fill ? " (fill)" : ""} */\nexport const ${name} = "${d}";`);
}

if (missing.length) {
    console.error(`[md3-icons] unknown Material Symbols: ${missing.join(", ")}`);
    process.exitCode = 1;
}

const header = `/* AUTO-GENERATED by scripts/generate-material-symbols.mjs — DO NOT EDIT.
 * Material Symbols Rounded (weight 400, viewBox "0 -960 960 960"), Apache-2.0.
 * Add an icon by importing \`mdSomeName\` from "@/components/md3/icons" and re-running the script.
 */
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${header}\n${entries.join("\n\n")}\n`);
console.log(`[md3-icons] wrote ${path.relative(webRoot, outPath)} (${entries.length} icons)`);
