#!/usr/bin/env bun
/**
 * Bundles the pure TypeScript MoeSekai Script (`.msk`) parser, compiler, runtime VM, stage layout
 * geometry, and asset domain config into a zero-dependency standalone ESM module at:
 *   docs/skills/moesekai-story-script/scripts/lib/msk-core.mjs
 *
 * This allows `docs/skills/moesekai-story-script/` to run completely standalone on plain Node 18+
 * (no `--experimental-strip-types`, no repository checkout, no npm install) when copied into any
 * third-party AI agent's skills directory.
 */
import { mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webDir = resolve(here, "..");
const repoRoot = resolve(webDir, "..");
const outFile = resolve(repoRoot, "docs/skills/moesekai-story-script/scripts/lib/msk-core.mjs");

const entrySource = `
export { ASSET_DOMAIN_BACKUP, ASSET_DOMAIN_MAIN } from ${JSON.stringify(resolve(webDir, "src/lib/assetDomains.ts"))};
export { live2dSources } from ${JSON.stringify(resolve(webDir, "src/lib/live2dViewer/config.ts"))};
export { compileStoryGraph } from ${JSON.stringify(resolve(webDir, "src/lib/storyMaker/compiler.ts"))};
export { detectStageActorOverlaps, layoutStageActors, STORY_LIMITS } from ${JSON.stringify(resolve(webDir, "src/lib/storyMaker/limits.ts"))};
export { advanceRuntime, createInitialRuntime } from ${JSON.stringify(resolve(webDir, "src/lib/storyMaker/runtime.ts"))};
export { parseStoryScript, serializeStoryScript } from ${JSON.stringify(resolve(webDir, "src/lib/storyMaker/script.ts"))};
export { STORY_REGIONS } from ${JSON.stringify(resolve(webDir, "src/types/storyMaker.ts"))};
`;

const tempEntry = join(tmpdir(), `moesekai-msk-core-entry-${process.pid}.ts`);
await writeFile(tempEntry, entrySource, "utf8");

try {
    const result = await Bun.build({
        entrypoints: [tempEntry],
        target: "node",
        format: "esm",
        minify: false,
        sourcemap: "none",
    });

    if (!result.success) {
        for (const log of result.logs) {
            console.error(log);
        }
        process.exit(1);
    }

    const code = await result.outputs[0].text();
    const banner = [
        "// AUTO-GENERATED by `bun run --cwd web build:msk-skill` (web/scripts/build-msk-skill-core.mjs).",
        "// Do not edit manually; modify web/src/lib/storyMaker/* and re-run the build script.",
        "",
    ].join("\n");

    await mkdir(dirname(outFile), { recursive: true });
    await writeFile(outFile, banner + code, "utf8");
    const sizeKb = (Buffer.byteLength(banner + code, "utf8") / 1024).toFixed(1);
    console.log(`Built standalone msk-core.mjs (${sizeKb} KB) -> ${outFile}`);
} finally {
    await rm(tempEntry, { force: true });
}
