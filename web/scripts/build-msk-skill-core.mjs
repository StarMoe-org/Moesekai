#!/usr/bin/env bun
/**
 * Bundles the pure TypeScript MoeSekai Script (`.msk`) parser, compiler, runtime VM, stage layout
 * geometry, and asset domain config into a zero-dependency standalone ESM module at:
 *   docs/skills/moesekai-story-script/scripts/lib/msk-core.mjs
 *
 * This allows `docs/skills/moesekai-story-script/` to run completely standalone on plain Node 18+
 * (no `--experimental-strip-types`, no repository checkout, no npm install) when copied into any
 * third-party AI agent's skills directory.
 */
import { mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webDir = resolve(here, "..");
const repoRoot = resolve(webDir, "..");
const outFile = resolve(repoRoot, "docs/skills/moesekai-story-script/scripts/lib/msk-core.mjs");
const coreEntry = fileURLToPath(import.meta.resolve("@moesekai/story-core"));

const entrySource = `
export {
    ASSET_DOMAIN_BACKUP,
    ASSET_DOMAIN_MAIN,
    STORY_LIMITS,
    STORY_REGIONS,
    advanceRuntime,
    applyStageActionWave,
    clampActorX,
    clampDelay,
    compileStoryGraph,
    computeActorRenderOrders,
    configureStoryCore,
    createInitialRuntime,
    detectStageActorOverlaps,
    extractLive2DMotionClips,
    fetchLive2DFormListing,
    fetchLive2DModelClips,
    fetchLive2DModels,
    fetchMotionBundleClips,
    findLeadingTelopEndIndex,
    getStageActionItems,
    inferLive2DMotionBundleCandidates,
    layoutStageActors,
    live2dAssetRequestPath,
    live2dDirectoryPath,
    live2dFormListingUrl,
    live2dListingUrl,
    live2dMemberUrl,
    live2dModelsFromListings,
    live2dMotionSet,
    live2dSiteListingUrl,
    live2dSources,
    live2dVersionedBaseUrl,
    parseStoryScript,
    resolveLive2DAssetDocument,
    resolveLive2DPublishedVersion,
    resolveLive2DSiteBase,
    serializeStoryScript,
} from ${JSON.stringify(coreEntry)};
`;

const tempEntry = join(tmpdir(), `moesekai-msk-core-entry-${process.pid}.ts`);
await writeFile(tempEntry, entrySource, "utf8");

try {
    const result = await Bun.build({
        entrypoints: [tempEntry],
        target: "node",
        format: "esm",
        minify: false,
        sourcemap: "none",
    });

    if (!result.success) {
        for (const log of result.logs) {
            console.error(log);
        }
        process.exit(1);
    }

    const code = await result.outputs[0].text();
    const banner = [
        "// AUTO-GENERATED by `bun run --cwd web build:msk-skill` (web/scripts/build-msk-skill-core.mjs).",
        "// Do not edit manually; update @moesekai/story-core and re-run the build script.",
        "",
    ].join("\n");

    await mkdir(dirname(outFile), { recursive: true });
    await writeFile(outFile, banner + code, "utf8");
    const sizeKb = (Buffer.byteLength(banner + code, "utf8") / 1024).toFixed(1);
    console.log(`Built standalone msk-core.mjs (${sizeKb} KB) -> ${outFile}`);
} finally {
    await rm(tempEntry, { force: true });
}
